// 병렬 호출용: 섹션 그룹 배열 반환
// ──────────────────────────────────────────────────────────────────
export function buildSajuPromptGroups(input: PromptInput): PromptGroup[] {
  const style = STYLE_BY_SLUG[input.productSlug] ?? STYLE_BY_SLUG["basic-saju"];
  const sajuData = buildSajuDataBlock(input);
  const totalGroups = style.groups.length;
  const manseryeokNote = input.manseryeokText
    ? " 천간지지·십성·대운·세운·신살 등 풀 명식 정보를 적극 근거로 활용하되, 단정적 표현은 피하고 가능성/경향으로 풀어 주세요."
    : " 4기둥 명식의 오행·기운을 근거로 자연스럽게 설명에 녹여 주세요.";

  return style.groups.map((group, idx) => {
    const partLabel = totalGroups > 1
      ? `[파트 ${idx + 1}/${totalGroups}: ${group.label}]\n이 파트의 섹션만 작성하세요. 다른 파트의 내용은 절대 포함하지 마세요.\n\n`
      : "";

    const user = `${sajuData}

==============================
■ 작성 지시 (반드시 그대로 따르세요)

이 리포트는 '${input.productName}' 상품을 위한 것입니다.
${partLabel}[분량] 약 ${group.length} — 각 섹션을 충분히 깊고 구체적으로, 이 분량을 반드시 채워 유료 상담 수준의 깊이로 작성하세요.
[구성] 아래 섹션 제목(##)을 그대로, 같은 순서로 사용하세요.

${group.sections}

위 사주 명식을 근거로, 위 섹션들을 풍성한 마크다운 리포트로 작성하세요.${manseryeokNote}`;

    return { label: group.label, system: SYSTEM_BASE, user };
  });
}

