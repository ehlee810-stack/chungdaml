// 내부 헬퍼: 사주 데이터 블록 생성
// ──────────────────────────────────────────────────────────────────
function buildSajuDataBlock(input: PromptInput): string {
  const m = input.myeongsik;
  const pillar = (p: { cheongan: string; jiji: string } | null) =>
    p ? `${p.cheongan}${p.jiji}` : "(시 미상)";

  const selfBody = input.manseryeokText
    ? input.manseryeokText
    : [
        `- 년주: ${pillar(m.year)}`,
        `- 월주: ${pillar(m.month)}`,
        `- 일주: ${pillar(m.day)}`,
        `- 시주: ${pillar(m.hour)}`,
      ].join("\n");

  const sajuSection = input.partnerSajuText
    ? `[${input.selfLabel ?? "첫 번째 사람"} 사주 명식]\n${selfBody}\n\n[${input.partnerLabel ?? "두 번째 사람"} 사주 명식]\n${input.partnerSajuText}`
    : `[사주 명식]\n${selfBody}`;

  const currentYear = new Date().getFullYear();

  return `${sajuSection}

[의뢰인 기본 정보]
- 생년월일: ${input.birthDate}${input.timeUnknown ? " (시 미상)" : input.birthTime ? ` ${input.birthTime}` : ""}
- 성별: ${input.gender === "male" ? "남성" : "여성"}
- 고민 키워드: ${input.concerns.length > 0 ? input.concerns.join(", ") : "(미입력)"}
- 현재 연도: ${currentYear}년 ("올해/내년"은 이 연도 기준)`;
}

